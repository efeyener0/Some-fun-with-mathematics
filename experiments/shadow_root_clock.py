#!/usr/bin/env python3
"""Shadow Root Clock: a minimal two-sided regular square-root extension.

The source algebra A has basis (1,h,q) and products

    h*h=q, q*q=q, h*q=1, q*h=-1.

There is no s in A with s*s=h.  Adjoining one unconstrained element is easy,
but asking the regular operators to be square roots as well is substantially
stronger:

    s*s=h,      L_s^2=L_h,      R_s^2=R_h.

This module constructs a sparse six-dimensional real extension with basis
(1,h,q,s,t,u), verifies those identities exactly, and exposes the small
signed-permutation group generated by L_s and R_s.  It also records the
dimension-six lower-bound certificate separately from the construction.

Only the Python standard library is used.  Every calculation is integral.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter, deque
from fractions import Fraction
from itertools import permutations, product
from math import comb
from typing import Iterable, Mapping, Sequence, TypeAlias


DIMENSION = 6
BASIS_LABELS = ("1", "h", "q", "s", "t", "u")
CORE_INDICES = (0, 1, 2)
SHADOW_INDICES = (3, 4, 5)
DEFAULT_TREE_LEAVES = 12
MAX_TREE_LEAVES = 30

Vector: TypeAlias = tuple[int, ...]
Matrix: TypeAlias = tuple[tuple[int, ...], ...]
SignedAction: TypeAlias = tuple[int, ...]
Word: TypeAlias = tuple[str, ...]


def unit_vector(index: int) -> Vector:
    return tuple(int(position == index) for position in range(DIMENSION))


BASIS = tuple(unit_vector(index) for index in range(DIMENSION))
ONE, H, Q, S, T, U = BASIS
ZERO = (0,) * DIMENSION


def _build_product_table() -> tuple[tuple[int, ...], ...]:
    """Return signed one-based basis codes; zero denotes the zero vector."""

    table = [[0] * DIMENSION for _ in range(DIMENSION)]

    # 1 is a two-sided unit.
    for index in range(DIMENSION):
        table[0][index] = index + 1
        table[index][0] = index + 1

    # The original three-dimensional algebra A.
    table[1][1] = 3       # h*h = q
    table[1][2] = 1       # h*q = 1
    table[2][1] = -1      # q*h = -1
    table[2][2] = 3       # q*q = q

    # The square-root clock.  L_s is a positive 6-cycle; R_s closes with a
    # negative sign.  These entries determine the h-actions required by the
    # two operator-square identities.
    table[3][3] = 2       # s*s = h
    table[3][1] = 5       # s*h = t
    table[1][3] = 5       # h*s = t
    table[3][4] = 3       # s*t = q
    table[4][3] = 3       # t*s = q
    table[3][2] = 6       # s*q = u
    table[2][3] = 6       # q*s = u
    table[3][5] = 1       # s*u = 1
    table[5][3] = -1      # u*s = -1

    table[1][4] = 6       # h*t = u
    table[4][1] = 6       # t*h = u
    table[1][5] = 4       # h*u = s
    table[5][1] = -4      # u*h = -s

    # All unmentioned non-unit products are zero.  This is one sparse
    # completion, not a claim that the rooted extension is unique.
    return tuple(tuple(row) for row in table)


PRODUCT_CODES = _build_product_table()


def vector_from_code(code: int) -> Vector:
    if code == 0:
        return ZERO
    sign = 1 if code > 0 else -1
    basis = BASIS[abs(code) - 1]
    return tuple(sign * coordinate for coordinate in basis)


def multiply_codes(left: int, right: int) -> int:
    if left == 0 or right == 0:
        return 0
    sign = (1 if left > 0 else -1) * (1 if right > 0 else -1)
    product_code = PRODUCT_CODES[abs(left) - 1][abs(right) - 1]
    return sign * product_code


def multiply(left: Sequence[int], right: Sequence[int]) -> Vector:
    if len(left) != DIMENSION or len(right) != DIMENSION:
        raise ValueError(f"vectors must have dimension {DIMENSION}")
    result = [0] * DIMENSION
    for left_index, left_coefficient in enumerate(left):
        if left_coefficient == 0:
            continue
        for right_index, right_coefficient in enumerate(right):
            if right_coefficient == 0:
                continue
            code = PRODUCT_CODES[left_index][right_index]
            if code == 0:
                continue
            sign = 1 if code > 0 else -1
            result[abs(code) - 1] += left_coefficient * right_coefficient * sign
    return tuple(result)


def vector_label(vector: Sequence[int]) -> str:
    if tuple(vector) == ZERO:
        return "0"
    terms: list[str] = []
    for coefficient, basis_label in zip(vector, BASIS_LABELS, strict=True):
        if coefficient == 0:
            continue
        magnitude = abs(coefficient)
        body = basis_label if magnitude == 1 else f"{magnitude}{basis_label}"
        if not terms:
            terms.append(f"-{body}" if coefficient < 0 else body)
        else:
            terms.append(f"{'-' if coefficient < 0 else '+'}{body}")
    return "".join(terms)


def code_label(code: int) -> str:
    return vector_label(vector_from_code(code))


def matrix_from_columns(columns: Sequence[Sequence[int]]) -> Matrix:
    if len(columns) != DIMENSION or any(len(column) != DIMENSION for column in columns):
        raise ValueError("matrix columns have the wrong shape")
    return tuple(
        tuple(columns[column][row] for column in range(DIMENSION))
        for row in range(DIMENSION)
    )


def left_matrix(element: Sequence[int]) -> Matrix:
    return matrix_from_columns(tuple(multiply(element, basis) for basis in BASIS))


def right_matrix(element: Sequence[int]) -> Matrix:
    return matrix_from_columns(tuple(multiply(basis, element) for basis in BASIS))


def identity_matrix() -> Matrix:
    return tuple(
        tuple(int(row == column) for column in range(DIMENSION))
        for row in range(DIMENSION)
    )


def matrix_multiply(left: Matrix, right: Matrix) -> Matrix:
    return tuple(
        tuple(
            sum(left[row][inner] * right[inner][column] for inner in range(DIMENSION))
            for column in range(DIMENSION)
        )
        for row in range(DIMENSION)
    )


def matrix_subtract(left: Matrix, right: Matrix) -> Matrix:
    return tuple(
        tuple(left[row][column] - right[row][column] for column in range(DIMENSION))
        for row in range(DIMENSION)
    )


def matrix_power(matrix: Matrix, exponent: int) -> Matrix:
    if exponent < 0:
        raise ValueError("matrix exponent must be non-negative")
    result = identity_matrix()
    factor = matrix
    remaining = exponent
    while remaining:
        if remaining & 1:
            result = matrix_multiply(result, factor)
        factor = matrix_multiply(factor, factor)
        remaining >>= 1
    return result


def principal_submatrix(matrix: Matrix, indices: Sequence[int]) -> Matrix:
    return tuple(tuple(matrix[row][column] for column in indices) for row in indices)


def determinant(matrix: Sequence[Sequence[int]]) -> int:
    """Exact Bareiss determinant for a square integer matrix."""

    size = len(matrix)
    if any(len(row) != size for row in matrix):
        raise ValueError("determinant requires a square matrix")
    if size == 0:
        return 1
    work = [list(row) for row in matrix]
    sign = 1
    previous_pivot = 1
    for pivot_index in range(size - 1):
        if work[pivot_index][pivot_index] == 0:
            swap_index = next(
                (row for row in range(pivot_index + 1, size) if work[row][pivot_index]),
                None,
            )
            if swap_index is None:
                return 0
            work[pivot_index], work[swap_index] = work[swap_index], work[pivot_index]
            sign = -sign
        pivot = work[pivot_index][pivot_index]
        for row in range(pivot_index + 1, size):
            for column in range(pivot_index + 1, size):
                numerator = work[row][column] * pivot - work[row][pivot_index] * work[pivot_index][column]
                if numerator % previous_pivot:
                    raise AssertionError("Bareiss division lost exactness")
                work[row][column] = numerator // previous_pivot
        previous_pivot = pivot
    return sign * work[-1][-1]


def matrix_rank(matrix: Sequence[Sequence[int]]) -> int:
    if not matrix:
        return 0
    width = len(matrix[0])
    work = [[Fraction(value) for value in row] for row in matrix]
    rank = 0
    for column in range(width):
        pivot = next((row for row in range(rank, len(work)) if work[row][column]), None)
        if pivot is None:
            continue
        work[rank], work[pivot] = work[pivot], work[rank]
        pivot_value = work[rank][column]
        work[rank] = [value / pivot_value for value in work[rank]]
        for row in range(len(work)):
            if row == rank or work[row][column] == 0:
                continue
            factor = work[row][column]
            work[row] = [
                value - factor * pivot_entry
                for value, pivot_entry in zip(work[row], work[rank], strict=True)
            ]
        rank += 1
        if rank == len(work):
            break
    return rank


def vector_subtract(left: Sequence[int], right: Sequence[int]) -> Vector:
    return tuple(left_value - right_value for left_value, right_value in zip(left, right, strict=True))


def associator(left: Sequence[int], middle: Sequence[int], right: Sequence[int]) -> Vector:
    return vector_subtract(
        multiply(multiply(left, middle), right),
        multiply(left, multiply(middle, right)),
    )


def nucleus_constraint_rows(slot: int) -> tuple[tuple[int, ...], ...]:
    if slot not in {0, 1, 2}:
        raise ValueError("nucleus slot must be 0, 1, or 2")
    rows: list[tuple[int, ...]] = []
    for first in BASIS:
        for second in BASIS:
            columns: list[Vector] = []
            for candidate in BASIS:
                arguments: list[Vector | None] = [None, None, None]
                arguments[slot] = candidate
                fixed = iter((first, second))
                for position in range(3):
                    if arguments[position] is None:
                        arguments[position] = next(fixed)
                if any(argument is None for argument in arguments):
                    raise AssertionError("nucleus argument assembly failed")
                left, middle, right = arguments
                assert left is not None and middle is not None and right is not None
                columns.append(associator(left, middle, right))
            for output in range(DIMENSION):
                rows.append(tuple(column[output] for column in columns))
    return tuple(rows)


def commutant_constraint_rows() -> tuple[tuple[int, ...], ...]:
    rows: list[tuple[int, ...]] = []
    for fixed in BASIS:
        columns = [
            vector_subtract(multiply(candidate, fixed), multiply(fixed, candidate))
            for candidate in BASIS
        ]
        for output in range(DIMENSION):
            rows.append(tuple(column[output] for column in columns))
    return tuple(rows)


def derivation_constraint_rows() -> tuple[tuple[int, ...], ...]:
    """Linear Leibniz constraints for all 6x6 derivation matrices."""

    unknowns = DIMENSION * DIMENSION
    rows: list[tuple[int, ...]] = []
    for left_index, left in enumerate(BASIS):
        for right_index, right in enumerate(BASIS):
            product_value = multiply(left, right)
            for output in range(DIMENSION):
                row = [0] * unknowns

                # D(left*right).
                for input_index, coefficient in enumerate(product_value):
                    row[output * DIMENSION + input_index] += coefficient

                # -D(left)*right - left*D(right).
                for image_index, image_basis in enumerate(BASIS):
                    row[image_index * DIMENSION + left_index] -= multiply(
                        image_basis, right
                    )[output]
                    row[image_index * DIMENSION + right_index] -= multiply(
                        left, image_basis
                    )[output]
                rows.append(tuple(row))
    return tuple(rows)


def apply_action_to_code(action: SignedAction, code: int) -> int:
    if code == 0:
        return 0
    return (1 if code > 0 else -1) * action[abs(code) - 1]


def signed_basis_automorphisms() -> tuple[SignedAction, ...]:
    """Exhaust every unit-fixing signed permutation; not all linear maps."""

    automorphisms: list[SignedAction] = []
    for tail_permutation in permutations(range(2, DIMENSION + 1)):
        for signs in product((-1, 1), repeat=DIMENSION - 1):
            action = (1,) + tuple(
                sign * image
                for sign, image in zip(signs, tail_permutation, strict=True)
            )
            if all(
                apply_action_to_code(action, PRODUCT_CODES[left][right])
                == multiply_codes(action[left], action[right])
                for left in range(DIMENSION)
                for right in range(DIMENSION)
            ):
                automorphisms.append(action)
    return tuple(automorphisms)


def structural_report() -> dict[str, object]:
    nucleus_ranks = tuple(
        matrix_rank(nucleus_constraint_rows(slot)) for slot in range(3)
    )
    if nucleus_ranks != (5, 5, 5):
        raise AssertionError("nucleus ranks changed")

    commutant_rows = commutant_constraint_rows()
    commutant_rank = matrix_rank(commutant_rows)
    if commutant_rank != 4:
        raise AssertionError("commutant rank changed")
    for candidate in (ONE, T):
        if any(
            sum(coefficient * coordinate for coefficient, coordinate in zip(row, candidate, strict=True))
            for row in commutant_rows
        ):
            raise AssertionError("declared commutant basis does not commute")

    associator_columns = tuple(
        associator(left, middle, right)
        for left in BASIS
        for middle in BASIS
        for right in BASIS
    )
    associator_rows = tuple(
        tuple(column[output] for column in associator_columns)
        for output in range(DIMENSION)
    )
    associator_rank = matrix_rank(associator_rows)

    derivation_rows = derivation_constraint_rows()
    derivation_rank = matrix_rank(derivation_rows)
    automorphisms = signed_basis_automorphisms()

    return {
        "left_nucleus": {"dimension": 1, "basis": ["1"]},
        "middle_nucleus": {"dimension": 1, "basis": ["1"]},
        "right_nucleus": {"dimension": 1, "basis": ["1"]},
        "commutant": {"dimension": DIMENSION - commutant_rank, "basis": ["1", "t"]},
        "center": {"dimension": 1, "basis": ["1"]},
        "associator": {
            "image_rank": associator_rank,
            "full_tensor_kernel_dimension": DIMENSION ** 3 - associator_rank,
        },
        "derivations": {
            "constraint_rank": derivation_rank,
            "space_dimension": DIMENSION * DIMENSION - derivation_rank,
        },
        "signed_basis_automorphisms": {
            "search_space": 2 ** (DIMENSION - 1) * 120,
            "count": len(automorphisms),
            "actions": [list(action) for action in automorphisms],
            "scope": "exact among unit-fixing signed-basis permutations; not a classification of all linear automorphisms",
        },
    }


def signed_action(matrix: Matrix) -> SignedAction:
    action: list[int] = []
    for column in range(DIMENSION):
        nonzero = [(row, matrix[row][column]) for row in range(DIMENSION) if matrix[row][column]]
        if len(nonzero) != 1 or abs(nonzero[0][1]) != 1:
            raise ValueError("matrix is not a signed-basis action")
        row, sign = nonzero[0]
        action.append(sign * (row + 1))
    if len({abs(value) for value in action}) != DIMENSION:
        raise ValueError("matrix is not a signed permutation")
    return tuple(action)


def compose_actions(left: SignedAction, right: SignedAction) -> SignedAction:
    """Return left-after-right, matching ordinary matrix multiplication."""

    composed: list[int] = []
    for image in right:
        outer = left[abs(image) - 1]
        composed.append((1 if image > 0 else -1) * outer)
    return tuple(composed)


IDENTITY_ACTION: SignedAction = tuple(range(1, DIMENSION + 1))


def action_power(action: SignedAction, exponent: int) -> SignedAction:
    result = IDENTITY_ACTION
    factor = action
    remaining = exponent
    while remaining:
        if remaining & 1:
            result = compose_actions(result, factor)
        factor = compose_actions(factor, factor)
        remaining >>= 1
    return result


def action_order(action: SignedAction) -> int:
    current = IDENTITY_ACTION
    for order in range(1, 1_000):
        current = compose_actions(current, action)
        if current == IDENTITY_ACTION:
            return order
    raise AssertionError("signed action order exceeded the finite search bound")


def enumerate_clock_group() -> tuple[dict[SignedAction, Word], tuple[int, ...]]:
    generators = (("L", signed_action(left_matrix(S))), ("R", signed_action(right_matrix(S))))
    words: dict[SignedAction, Word] = {IDENTITY_ACTION: ()}
    queue = deque([IDENTITY_ACTION])
    while queue:
        state = queue.popleft()
        for label, generator in generators:
            successor = compose_actions(state, generator)
            if successor in words:
                continue
            words[successor] = words[state] + (label,)
            queue.append(successor)
    depth_counts = Counter(map(len, words.values()))
    profile = tuple(depth_counts[depth] for depth in range(max(depth_counts) + 1))
    return words, profile


def expected_clock_group(left_action: SignedAction) -> frozenset[SignedAction]:
    absolute_rotations = {
        tuple(abs(value) for value in action_power(left_action, exponent))
        for exponent in range(6)
    }
    return frozenset(
        tuple(sign * image for sign, image in zip(signs, rotation, strict=True))
        for rotation in absolute_rotations
        for signs in product((-1, 1), repeat=DIMENSION)
    )


def catalan(index: int) -> int:
    if index < 0:
        raise ValueError("Catalan index must be non-negative")
    return comb(2 * index, index) // (index + 1)


def repeated_s_ecology(max_leaves: int) -> tuple[dict[str, object], ...]:
    if not 1 <= max_leaves <= MAX_TREE_LEAVES:
        raise ValueError(f"max leaves must be between 1 and {MAX_TREE_LEAVES}")
    counts: list[Counter[int]] = [Counter(), Counter({4: 1})]
    rows: list[dict[str, object]] = []
    for leaves in range(1, max_leaves + 1):
        if leaves >= 2:
            current: Counter[int] = Counter()
            for left_leaves in range(1, leaves):
                right_leaves = leaves - left_leaves
                for left_code, left_count in counts[left_leaves].items():
                    for right_code, right_count in counts[right_leaves].items():
                        current[multiply_codes(left_code, right_code)] += left_count * right_count
            counts.append(current)
        current = counts[leaves]
        if sum(current.values()) != catalan(leaves - 1):
            raise AssertionError("tree ecology lost a Catalan bracketing")
        ordered_codes = tuple(range(-DIMENSION, 0)) + (0,) + tuple(range(1, DIMENSION + 1))
        histogram = {
            code_label(code): current[code]
            for code in ordered_codes
            if current[code]
        }
        rows.append(
            {
                "leaves": leaves,
                "trees": catalan(leaves - 1),
                "phenotypes": len(current),
                "histogram": histogram,
            }
        )
    return tuple(rows)


def comb_sequences(length: int) -> dict[str, list[str]]:
    if length < 1:
        raise ValueError("comb length must be positive")
    left_code = 4
    right_code = 4
    left = [code_label(left_code)]
    right = [code_label(right_code)]
    for _ in range(2, length + 1):
        left_code = multiply_codes(left_code, 4)
        right_code = multiply_codes(4, right_code)
        left.append(code_label(left_code))
        right.append(code_label(right_code))
    return {"left_comb": left, "right_comb": right}



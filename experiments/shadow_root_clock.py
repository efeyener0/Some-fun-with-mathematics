def bounded_leaves(value: str) -> int:
    parsed = int(value)
    if not 1 <= parsed <= MAX_TREE_LEAVES:
        raise argparse.ArgumentTypeError(f"must be between 1 and {MAX_TREE_LEAVES}")
    return parsed


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Explore the minimal six-dimensional two-sided square-root clock.",
        epilog="With no command, print the exact report and repeated-s ecology.",
    )
    subparsers = parser.add_subparsers(dest="command")

    report = subparsers.add_parser("report", help="print the construction and its exact invariants")
    report.add_argument("--max-leaves", type=bounded_leaves, default=DEFAULT_TREE_LEAVES)
    report.add_argument("--json", action="store_true", help="emit deterministic JSON")
    report.add_argument("--deep", action="store_true", help="also check all 384^2 group products")

    subparsers.add_parser("table", help="print the sparse multiplication table")

    ecology = subparsers.add_parser("ecology", help="count every repeated-s bracketing")
    ecology.add_argument("--max-leaves", type=bounded_leaves, default=DEFAULT_TREE_LEAVES)
    ecology.add_argument("--json", action="store_true", help="emit deterministic JSON")

    test = subparsers.add_parser("test", help="run exact embedded checks")
    test.add_argument("--deep", action="store_true", help="also check all 147456 group products")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        if args.command == "table":
            print_table()
        elif args.command == "ecology":
            rows = list(repeated_s_ecology(args.max_leaves))
            if args.json:
                print(json.dumps(rows, indent=2, sort_keys=True))
            else:
                print_human(build_report(args.max_leaves, False))
        elif args.command == "test":
            run_self_tests(args.deep)
        else:
            max_leaves = args.max_leaves if args.command == "report" else DEFAULT_TREE_LEAVES
            deep = bool(args.deep) if args.command == "report" else False
            report = build_report(max_leaves, deep)
            if args.command == "report" and args.json:
                print(json.dumps(report, indent=2, sort_keys=True))
            else:
                print_human(report)
    except ValueError as error:
        parser.error(str(error))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

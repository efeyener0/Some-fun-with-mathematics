def operator_report(deep: bool) -> dict[str, object]:
    left_s = left_matrix(S)
    right_s = right_matrix(S)
    left_h = left_matrix(H)
    right_h = right_matrix(H)
    left_action = signed_action(left_s)
    right_action = signed_action(right_s)

    if matrix_multiply(left_s, left_s) != left_h:
        raise AssertionError("L_s^2 != L_h")
    if matrix_multiply(right_s, right_s) != right_h:
        raise AssertionError("R_s^2 != R_h")

    words, depth_profile = enumerate_clock_group()
    expected = expected_clock_group(left_action)
    if frozenset(words) != expected:
        raise AssertionError("clock group is not the expected signed cyclic wreath product")

    pair_checks = 0
    if deep:
        states = tuple(words)
        state_set = frozenset(states)
        for left in states:
            for right in states:
                if compose_actions(left, right) not in state_set:
                    raise AssertionError("clock group failed pairwise closure")
                pair_checks += 1

    left_defect = matrix_subtract(left_s, right_s)
    h_defect = matrix_subtract(left_h, right_h)
    order_histogram = Counter(action_order(state) for state in words)
    canonical_payload = [
        {"state": list(state), "word": "".join(words[state])}
        for state in sorted(words)
    ]
    group_fingerprint = hashlib.sha256(
        json.dumps(canonical_payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()

    return {
        "actions": {
            "L_s": list(left_action),
            "R_s": list(right_action),
            "L_h": list(signed_action(left_h)),
            "R_h": list(signed_action(right_h)),
        },
        "root_identities": {"L_s_squared_equals_L_h": True, "R_s_squared_equals_R_h": True},
        "orders": {"L_s": 6, "R_s": 12, "L_h": 3, "R_h": 6},
        "determinants": {
            "L_s": determinant(left_s),
            "R_s": determinant(right_s),
            "L_h_core": determinant(principal_submatrix(left_h, CORE_INDICES)),
            "L_h_shadow": determinant(principal_submatrix(left_h, SHADOW_INDICES)),
            "L_h_full": determinant(left_h),
            "R_h_core": determinant(principal_submatrix(right_h, CORE_INDICES)),
            "R_h_shadow": determinant(principal_submatrix(right_h, SHADOW_INDICES)),
            "R_h_full": determinant(right_h),
        },
        "chirality_defects": {
            "rank_L_s_minus_R_s": matrix_rank(left_defect),
            "square_L_s_minus_R_s_is_zero": matrix_multiply(left_defect, left_defect) == tuple(tuple(0 for _ in range(DIMENSION)) for _ in range(DIMENSION)),
            "rank_L_h_minus_R_h": matrix_rank(h_defect),
            "square_L_h_minus_R_h_is_zero": matrix_multiply(h_defect, h_defect) == tuple(tuple(0 for _ in range(DIMENSION)) for _ in range(DIMENSION)),
        },
        "generated_group": {
            "order": len(words),
            "structure": "C2^6 semidirect C6 (finite wreath product C2 wr C6)",
            "shortlex_depth_profile": list(depth_profile),
            "maximum_shortlex_depth": max(map(len, words.values())),
            "element_order_histogram": {str(order): count for order, count in sorted(order_histogram.items())},
            "pairwise_closure_checks": pair_checks,
            "fingerprint": group_fingerprint,
        },
    }


def multiplication_table_report() -> list[list[str]]:
    return [[code_label(code) for code in row] for row in PRODUCT_CODES]


